    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        crearObjetoProducto();
        dao.guardar(producto);
        JOptionPane.showMessageDialog(null, "Registro creado correctamente", "Guardar", 2);
        consultarProductos();
        limpiarControles();
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBorrarActionPerformed
        // TODO add your handling code here:
        int result = JOptionPane.showConfirmDialog(null, "Eliminar el registro?", "Eliminar", JOptionPane.YES_NO_OPTION);
        if (result == 0) {
            dao.eliminar(Integer.valueOf(lblId.getText()));
            consultarProductos();
            limpiarControles();
        }
    }//GEN-LAST:event_btnBorrarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        int result = JOptionPane.showConfirmDialog(null, "Actualizar el registro?", "Actualizar", JOptionPane.YES_NO_OPTION);
        if (result == 0) {
            crearObjetoProducto();
            dao.actualizar(producto);
            consultarProductos();
            limpiarControles();
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void tablaProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaProductosMouseClicked
        // TODO add your handling code here:
        int fila = tablaProductos.getSelectedRow();
        if (fila == -1) {
            return;
        }
        lblId.setText(tablaProductos.getValueAt(fila, 0).toString());
        txtNombre.setText(tablaProductos.getValueAt(fila, 1).toString());
        txtDescripcion.setText(tablaProductos.getValueAt(fila, 2).toString());
        txtPrecio.setText(tablaProductos.getValueAt(fila, 3).toString());
        txtCantidad.setText(tablaProductos.getValueAt(fila, 4).toString());
    }//GEN-LAST:event_tablaProductosMouseClicked

    public void limpiarControles() {
        lblId.setText("0");
        txtNombre.setText("");
        txtDescripcion.setText("");
        txtPrecio.setText("");
        txtCantidad.setText("");
    }

    public void crearObjetoProducto() {
        int id = 0;
        if (!lblId.getText().equals("0")) {
            id = Integer.valueOf(lblId.getText());
        }

        String nombre = txtNombre.getText();
        String descripcion = txtDescripcion.getText();
        double precio = Double.valueOf(txtPrecio.getText());
        int cantidad = Integer.valueOf(txtCantidad.getText());

        producto = new Producto(id, nombre, descripcion, precio, cantidad);
    }

    public void consultarProductos() {
        try {
            ProductoDAO dao = new ProductoDAO();
            modelo.setRowCount(0);
            for (Producto p : dao.consultar()) {
                modelo.addRow(new Object[]{
                    p.getIdProducto(),
                    p.getNombre(),
                    p.getDescripcion(),
                    p.getPrecio(),
                    p.getCantidad()
                });
            }
        } catch (Exception ex) {
            System.out.println("Error = " + ex.toString());
        }
    }
